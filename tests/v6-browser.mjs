import { chromium } from 'playwright';
const origin=process.env.STEP_URL||'http://127.0.0.1:4174/';
const base=origin.endsWith('/')?origin:origin+'/';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('https://www.gstatic.com/firebasejs/**',async r=>{
  const u=r.request().url();
  let body='';
  if(u.endsWith('firebase-app.js'))body='export const initializeApp=()=>({});';
  else if(u.endsWith('firebase-auth.js'))body='export const getAuth=()=>({});export const setPersistence=async()=>{};export const browserLocalPersistence={};export const signInWithEmailAndPassword=async()=>{};export const onAuthStateChanged=(a,f)=>{f({uid:"test-v6"});return()=>{}};export const signOut=async()=>{};';
  else if(u.endsWith('firebase-firestore.js'))body='export const getFirestore=()=>({});export const doc=(...x)=>({path:x});export const onSnapshot=(r,f)=>{f({exists:()=>false});return()=>{}};export const runTransaction=async(db,f)=>f({get:async()=>({exists:()=>false}),set:()=>{}});export const serverTimestamp=()=>new Date();';
  await r.fulfill({status:200,contentType:'application/javascript',headers:{'access-control-allow-origin':'*'},body});
});
await page.goto(base+'app/v6/',{waitUntil:'domcontentloaded'});
await page.waitForSelector('#left .toolbar',{timeout:20000});
if(await page.locator('#gate:visible').count())throw Error('Login gate stayed visible');
await page.locator('[data-a="add"]').first().click();
await page.locator('#modal input[name=title]').fill('실사용 확인');
await page.locator('#modal button[type=submit]').click();
if(await page.locator('#modal:visible').count())throw Error('Add modal did not close');
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('step_v6_live_v1')));
if(saved.tasks.length!==1||saved.tasks[0].title!=='실사용 확인')throw Error('Task creation/persistence failed');
await page.locator('[data-a="detail"]').first().click();
await page.locator('#right [data-a="edit"]').click();
await page.locator('#modal [name=mode]').selectOption('focus');
await page.locator('#modal [name=kind]').selectOption('study');
await page.locator('#modal button[type=submit]').click();
await page.locator('#right [data-a="run"]').click();
await page.locator('#right [data-a="check"][data-i="0"]').click();
await page.locator('#cue').fill('노트 3쪽 다시 열기');
await page.locator('#right [data-a="pause"]').click();
await page.locator('#dock [data-a="resume"]').click();
const checks=await page.evaluate(()=>JSON.parse(localStorage.getItem('step_v6_live_v1')).tasks[0]);
if(!checks.checks[0]||checks.resume!=='노트 3쪽 다시 열기')throw Error('Pause/resume state lost');
await page.locator('#right [data-a="step-done"]').click();
if(!await page.locator('#right [data-a="complete"]').count())throw Error('Final completion gate missing');
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth);
if(overflow)throw Error('390px horizontal overflow');
await page.setViewportSize({width:820,height:1100});
const twoColumns=await page.evaluate(()=>getComputedStyle(document.querySelector('#layout')).display==='grid');
if(!twoColumns)throw Error('iPad two-pane layout missing');
await page.setViewportSize({width:1366,height:850});
if(await page.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth))throw Error('Mac horizontal overflow');
if(errors.length)throw Error('Browser errors: '+errors.join(' | '));
await browser.close();
console.log('Step v6 browser flow passed');
